// ─── FreeRTOS Task Configuration ────────────────────────────────────────────
// Stack sizes are ~2x the peaks measured on the ESP32-S3 (task 3b.8/3b.9); the
// diag command (cmd/<thing>/diag) reports the live high-water marks.
#define WIFI_TASK_STACK_SIZE    4096
#define MQTT_TASK_STACK_SIZE    8192    // measured peak 3.8 KB (classical + ML-DSA handshakes; wolfSSL buffers are on the heap)
#define BLINK_TASK_STACK_SIZE   2048
#define OTA_TASK_STACK_SIZE     24576   // measured peak 11.7 KB (ML-DSA-signed OTA verify)
#define LOOP_TASK_STACK_SIZE    4096    // Arduino loop(); measured peak ~2 KB (core default 8 KB)
#define OTA_URL_MAX             2048    // presigned S3 URL is ~1500 bytes; 1024 truncated it
#define WIFI_TASK_PRIORITY      1
#define MQTT_TASK_PRIORITY      1
#define BLINK_TASK_PRIORITY     0       // Lowest priority — just visual indicator
#define OTA_TASK_PRIORITY       2       // Above MQTT so download runs promptly
#define WIFI_TASK_CORE          0       // Run WiFi on core 0
#define MQTT_TASK_CORE          1       // Run MQTT on core 1 (if available)

// ─── Firmware Version ───────────────────────────────────────────────────────
// Single canonical version per variant. CodeBuild injects FIRMWARE_VERSION into
// secrets.h (from variants.json), so the value the device reports in telemetry
// is identical to the S3 artifact dir and the OTA job version — the dashboard,
// firmware bucket, and device all agree. The variant default is only a
// fallback for a local/desktop build where secrets.h did not set it.
#ifndef FIRMWARE_VERSION
#define FIRMWARE_VERSION VARIANT_DEFAULT_VERSION
#endif

// ─── OTA Firmware Signature Era ─────────────────────────────────────────────
// The signature algorithm that signed THIS firmware IMAGE for OTA delivery —
// distinct from CERT_SIGNATURE_ALG (variant_config.h), which is the TLS
// *certificate* signature. The signing era is a property of the VERSION, so
// CodeBuild injects FIRMWARE_OTA_SIG_ALG into secrets.h from the build's
// SIGNER_ERA ("ECDSA-P256" for the classical signer era, "ML-DSA-44" for the
// ML-DSA signer era, "unsigned" for a USB/trusted factory flash). Reported in
// telemetry so the dashboard can show which signature protected the running
// image. This #define is only a fallback for a local build.
#ifndef FIRMWARE_OTA_SIG_ALG
#define FIRMWARE_OTA_SIG_ALG "unsigned"
#endif

