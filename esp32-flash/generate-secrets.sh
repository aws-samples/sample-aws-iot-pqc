#!/bin/bash
# ─────────────────────────────────────────────────────────────────────────────
# generate-secrets.sh
#
# Generates a single secrets.h file with the shared fleet certificate
# and broker IP. Since all devices share the same firmware binary and
# fleet cert (identity comes from MAC address at runtime), only ONE
# secrets.h file is needed for all devices.
#
# Usage:
#   ./generate-secrets.sh <broker-ip> [certs-dir]
#
# Example:
#   WIFI_SSID=reinvent-iot WIFI_PASSWORD=aws2026 ./generate-secrets.sh 192.168.1.100
#
# Prerequisites:
#   - Fleet certificate copied from the Pi:
#     scp pi@<pi-ip>:~/Sample-aws-iot-pqc/greengrass/certs/output/ca.crt ./
#     scp pi@<pi-ip>:~/Sample-aws-iot-pqc/greengrass/certs/output/fleet-device.crt ./
#     scp pi@<pi-ip>:~/Sample-aws-iot-pqc/greengrass/certs/output/fleet-device.key ./
#
# Copyright 2024-2026 Amazon.com, Inc. or its affiliates. All Rights Reserved.
# SPDX-License-Identifier: MIT-0
# ─────────────────────────────────────────────────────────────────────────────

set -euo pipefail

BROKER_IP="${1:-}"
CERTS_DIR="${2:-.}"
WIFI_SSID="${WIFI_SSID:-WORKSHOP_WIFI}"
WIFI_PASSWORD="${WIFI_PASSWORD:-WORKSHOP_PASSWORD}"

if [[ -z "$BROKER_IP" ]]; then
    echo "Usage: $0 <broker-ip> [certs-dir]"
    echo ""
    echo "Arguments:"
    echo "  broker-ip   IP address of the Raspberry Pi running Mosquitto"
    echo "  certs-dir   Directory containing ca.crt, fleet-device.crt, fleet-device.key"
    echo ""
    echo "Environment variables:"
    echo "  WIFI_SSID      WiFi network name (default: WORKSHOP_WIFI)"
    echo "  WIFI_PASSWORD   WiFi password (default: WORKSHOP_PASSWORD)"
    echo ""
    echo "Example:"
    echo "  WIFI_SSID=reinvent-iot WIFI_PASSWORD=aws2026 $0 192.168.1.100"
    exit 1
fi

# Check required cert files
for f in ca.crt fleet-device.crt fleet-device.key; do
    if [[ ! -f "$CERTS_DIR/$f" ]]; then
        echo "[ERROR] Missing: $CERTS_DIR/$f"
        echo ""
        echo "Copy certs from Pi:"
        echo "  scp pi@<pi-ip>:~/Sample-aws-iot-pqc/greengrass/certs/output/ca.crt ."
        echo "  scp pi@<pi-ip>:~/Sample-aws-iot-pqc/greengrass/certs/output/fleet-device.crt ."
        echo "  scp pi@<pi-ip>:~/Sample-aws-iot-pqc/greengrass/certs/output/fleet-device.key ."
        exit 1
    fi
done

CA_CERT=$(cat "$CERTS_DIR/ca.crt")
DEVICE_CERT=$(cat "$CERTS_DIR/fleet-device.crt")
DEVICE_KEY=$(cat "$CERTS_DIR/fleet-device.key")

OUTPUT_FILE="./secrets.h"

cat > "$OUTPUT_FILE" << SECRETS_EOF
/*
 * secrets.h — PQC Workshop (shared fleet configuration)
 *
 * Generated by generate-secrets.sh
 * This single file works for ALL devices (identity from MAC address).
 *
 * DO NOT COMMIT THIS FILE (contains real credentials)
 */

#ifndef SECRETS_H
#define SECRETS_H

// ─── WiFi Configuration ─────────────────────────────────────────────────────
#define WIFI_SSID     "$WIFI_SSID"
#define WIFI_PASSWORD "$WIFI_PASSWORD"

// ─── Logging Configuration ──────────────────────────────────────────────────
#define LOG_LEVEL  3  // INFO

// ─── MQTT Broker (Mosquitto on Raspberry Pi) ────────────────────────────────
#define MQTT_BROKER_ENDPOINT "$BROKER_IP"
#define MQTT_BROKER_PORT     8883

// Device identity is derived at runtime from the ESP32 MAC address.
// Format: "esp32-XXYYZZ" (last 3 bytes of MAC). Unique per device.

// AWS IoT Core endpoint (reference — device connects via Mosquitto bridge)
#define AWS_IOT_ENDPOINT "unused-connects-via-bridge"
#define AWS_IOT_PORT     8883

// ─── Broker CA Certificate ──────────────────────────────────────────────────
static const char AWS_CERT_CA[] PROGMEM = R"EOF(
$CA_CERT
)EOF";

// ─── Fleet Device Certificate (shared by all workshop devices) ──────────────
static const char AWS_CERT_CRT[] PROGMEM = R"KEY(
$DEVICE_CERT
)KEY";

// ─── Fleet Device Private Key ───────────────────────────────────────────────
static const char AWS_CERT_PRIVATE[] PROGMEM = R"KEY(
$DEVICE_KEY
)KEY";

#endif // SECRETS_H
SECRETS_EOF

echo "═══════════════════════════════════════════════════════════════"
echo "  secrets.h generated!"
echo "═══════════════════════════════════════════════════════════════"
echo ""
echo "  File: $OUTPUT_FILE"
echo "  Broker: $BROKER_IP:8883"
echo "  WiFi: $WIFI_SSID"
echo ""
echo "  This single file works for ALL devices."
echo "  Copy it to both firmware sketch folders:"
echo "    cp secrets.h ../aws_iot_pqc_esp32/secrets.h"
echo "    cp secrets.h ../aws_iot_pqc_esp32_v1_classical/secrets.h"
echo ""
echo "  Then compile both firmwares in Arduino IDE and flash."
echo ""
